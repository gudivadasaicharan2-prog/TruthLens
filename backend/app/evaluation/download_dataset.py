"""
Dataset Downloader Information Utility for TruthLens Evaluation
============================================================
Displays dataset information without automatic downloading.
"""

import sys
from pathlib import Path
from typing import Dict, List, Optional
import argparse

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent.parent))


class DatasetDownloader:
    """
    Dataset downloader information utility.
    
    Displays dataset information without automatic downloading.
    """
    
    # Dataset metadata
    DATASETS = {
        'genimage': {
            'name': 'GenImage',
            'type': 'AI',
            'purpose': 'Generalization benchmark for AI-generated images from various generative models',
            'status': 'Not downloaded',
            'approx_size': 'Unknown',
            'destination': 'TruthLensDataset/evaluation/genimage',
            'source_url': 'https://github.com/GenImage-AI/GenImage',
            'description': 'Contains AI-generated images from various generative models for evaluation of AI detection systems.'
        },
        'diffusiondb': {
            'name': 'DiffusionDB',
            'type': 'AI',
            'purpose': 'Generalization benchmark for diffusion model outputs',
            'status': 'Not downloaded',
            'approx_size': 'Unknown',
            'destination': 'TruthLensDataset/evaluation/diffusiondb',
            'source_url': 'https://github.com/poloclub/diffusiondb',
            'description': 'Contains images generated by diffusion models (Stable Diffusion, DALL-E, etc.) for AI detection evaluation.'
        },
        'coco': {
            'name': 'COCO',
            'type': 'Real',
            'purpose': 'Generalization benchmark for real photographs',
            'status': 'Not downloaded',
            'approx_size': '~18 GB (full dataset)',
            'destination': 'TruthLensDataset/evaluation/coco',
            'source_url': 'https://cocodataset.org/',
            'description': 'Common Objects in Context dataset containing real photographs for evaluation of real image detection.'
        },
        'raise': {
            'name': 'RAISE',
            'type': 'Real',
            'purpose': 'Generalization benchmark for high-quality real photographs',
            'status': 'Not downloaded',
            'approx_size': '~4 GB',
            'destination': 'TruthLensDataset/evaluation/raise',
            'source_url': 'https://github.com/andreyto/raise-dataset',
            'description': 'Raw Image Archive for Scientific Image Evaluation containing high-quality real photographs.'
        }
    }
    
    def __init__(self, base_path: str = "TruthLensDataset/evaluation"):
        """
        Initialize dataset downloader.
        
        Args:
            base_path: Base path for evaluation datasets
        """
        self.base_path = Path(base_path)
    
    def list_datasets(self):
        """
        List all available evaluation datasets with information.
        
        Prints formatted list of datasets.
        """
        print("-" * 50)
        print("Available Evaluation Datasets")
        print("-" * 50)
        print()
        
        for dataset_key, dataset_info in self.DATASETS.items():
            print(f"{dataset_info['name']}")
            print(f"Type: {dataset_info['type']}")
            print(f"Purpose:")
            print(f"{dataset_info['purpose']}")
            print()
            print(f"Status:")
            print(f"{dataset_info['status']}")
            print()
            print(f"Approx Size:")
            print(f"{dataset_info['approx_size']}")
            print()
            print(f"Destination:")
            print(f"{dataset_info['destination']}")
            print()
            print("-" * 50)
    
    def show_dataset_info(self, dataset_name: str):
        """
        Show detailed information for a specific dataset.
        
        Args:
            dataset_name: Name of dataset to display info for
        """
        dataset_key = dataset_name.lower()
        
        if dataset_key not in self.DATASETS:
            print(f"Error: Dataset '{dataset_name}' not found.")
            print(f"Available datasets: {', '.join(self.DATASETS.keys())}")
            return
        
        dataset_info = self.DATASETS[dataset_key]
        
        print("=" * 80)
        print(f"Dataset Information: {dataset_info['name']}")
        print("=" * 80)
        print()
        
        print(f"Name:")
        print(f"  {dataset_info['name']}")
        print()
        
        print(f"Type:")
        print(f"  {dataset_info['type']}")
        print()
        
        print(f"Purpose:")
        print(f"  {dataset_info['purpose']}")
        print()
        
        print(f"Description:")
        print(f"  {dataset_info['description']}")
        print()
        
        print(f"Status:")
        print(f"  {dataset_info['status']}")
        print()
        
        print(f"Approximate Size:")
        print(f"  {dataset_info['approx_size']}")
        print()
        
        print(f"Destination:")
        print(f"  {dataset_info['destination']}")
        print()
        
        print(f"Source URL:")
        print(f"  {dataset_info['source_url']}")
        print()
        
        # Check if dataset already exists
        dataset_path = self.base_path / dataset_key
        if dataset_path.exists():
            print(f"Note: Dataset folder already exists at {dataset_path}")
        else:
            print(f"Note: Dataset folder does not exist yet.")
        
        print()
        print("=" * 80)
    
    def get_dataset_info(self, dataset_name: str) -> Optional[Dict]:
        """
        Get dataset information dictionary.
        
        Args:
            dataset_name: Name of dataset
        
        Returns:
            Dataset info dictionary or None if not found
        """
        dataset_key = dataset_name.lower()
        return self.DATASETS.get(dataset_key)
    
    def get_all_datasets(self) -> List[str]:
        """
        Get list of all available dataset names.
        
        Returns:
            List of dataset names
        """
        return list(self.DATASETS.keys())


def main():
    """CLI entry point for dataset downloader information."""
    parser = argparse.ArgumentParser(
        description='Display information about evaluation datasets (no automatic download)'
    )
    parser.add_argument(
        '--list',
        action='store_true',
        help='List all available evaluation datasets'
    )
    parser.add_argument(
        '--info',
        type=str,
        help='Show detailed information for a specific dataset'
    )
    
    args = parser.parse_args()
    
    downloader = DatasetDownloader()
    
    if args.list:
        downloader.list_datasets()
    elif args.info:
        downloader.show_dataset_info(args.info)
    else:
        print("No action specified. Use --list to see available datasets or --info <dataset> for details.")
        print()
        print("Available datasets:")
        for dataset in downloader.get_all_datasets():
            print(f"  - {dataset}")


if __name__ == "__main__":
    main()
